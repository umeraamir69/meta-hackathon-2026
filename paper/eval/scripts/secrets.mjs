const HEX = 'abcdef0123456789';
const AWS_ALNUM = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

export function tok(n, alphabet = ALNUM) {
  let out = '';
  while (out.length < n) out += alphabet;
  return out.slice(0, n);
}

