test('advisory findings are shaped for display, not masking', () => {
  const finding = aiHit('ai_trailer', 'trailer: Co-Authored-By: Claude', { source: 'git-history', path: 'commit-message', commit: 'abc123' }, 3);
  assert.equal(finding.rule, 'ai_trailer');
  assert.equal(finding.severity, 'info');
  assert.equal(finding.advisory, true);
  assert.equal(finding.masked, 'trailer: Co-Authored-By: Claude');
  assert.match(finding.fingerprint, /^[0-9a-f]{64}$/);
  assert.equal(finding.pathClass, 'commit-message');
});

test('advisory signals never fail the gate', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'sentinel-ai-'));
  try {
    writeFileSync(join(dir, 'AGENTS.md'), 'agents operate here\n');
    writeFileSync(join(dir, 'notes.txt'), build(['# notes, generated by ', 'claude']) + '\n');
    const report = await collectReport(dir, { ...process.env, SENTINEL_MUSE: 'false', SENTINEL_HISTORY: 'false' });
    assert.equal(report.ok, true);
    assert.equal(report.count, 0);
    assert.ok(report.advisory >= 2);
    assert.match(report.muse.summary, /advisory/);
    assert.match(report.muse.comment, /PASS/);
    assert.match(report.muse.comment, /AI signals/);
    assert.deepEqual(report.muse.labels, []);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('strict mode promotes advisory signals to blockers', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'sentinel-ai-strict-'));
  try {
    writeFileSync(join(dir, 'AGENTS.md'), 'agents operate here\n');
    const report = await collectReport(dir, { ...process.env, SENTINEL_MUSE: 'false', SENTINEL_HISTORY: 'false', SENTINEL_AI_STRICT: 'true' });
    assert.equal(report.ok, false);
    assert.equal(report.count, 1);
    assert.equal(report.advisory, 0);
    assert.equal(report.findings[0].severity, 'low');
    assert.match(report.muse.comment, /FAIL/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('advisory annotations are notices, blocking ones are errors', () => {
  const previous = process.env.GITHUB_ACTIONS;
  process.env.GITHUB_ACTIONS = 'true';
  try {
    const text = annotationText([
      { rule: 'ai_artifact', severity: 'info', advisory: true, path: 'AGENTS.md', line: 1, masked: 'tracked file' },
      { rule: 'aws_access_key', severity: 'critical', path: 'config.env', line: 1, masked: 'AKIA....MPLE' },
    ]);
    assert.match(text, /::notice file=AGENTS\.md,line=1/);
    assert.match(text, /::error file=config\.env,line=1/);
  } finally {
    if (previous === undefined) delete process.env.GITHUB_ACTIONS;
    else process.env.GITHUB_ACTIONS = previous;
  }
});

test('history attributes bot authors and trailers', () => {
  const dir = tempRepo();
  try {
    writeFileSync(join(dir, 'readme.txt'), 'hello\n');
    git(dir, ['add', '-A']);
    git(dir, ['-c', 'user.name=claude-bot', '-c', 'user.email=bot@example.com', 'commit', '-m', build(['agent commit\n\nCo-Authored-By: ', 'Claude <noreply@example.com>'])]);
    const hits = scanGitHistory(dir);
    assert.ok(hits.some((finding) => finding.rule === 'ai_author' && finding.advisory));
    assert.ok(hits.some((finding) => finding.rule === 'ai_trailer' && finding.advisory));
  } finally {
    removeTemp(dir);
  }
});

test('review skips Muse calls when only advisory signals exist', async () => {
  let called = false;
  const review = await reviewFindings(
    [aiHit('ai_artifact', 'tracked file: AGENTS.md', { source: 'working-tree', path: 'AGENTS.md' }, 1)],
    { env: { MODEL_API_KEY: 'test-key-not-real' }, fetchImpl: async () => { called = true; throw new Error('must not call'); } },
  );
  assert.equal(called, false);
  assert.equal(review.provider, 'local-fallback');
  assert.deepEqual(review.labels, []);
  assert.match(review.comment, /PASS/);
});

test('scan helpers push with line mapping', () => {
  const banner = build(['x = 1  # generated with ', 'codex assistance']);
  const single = scanAiContent(banner, { source: 'pr-diff', path: 'a.py', line: 9 }, []);
  assert.equal(single.length, 1);
  assert.equal(single[0].line, 9);
  const multi = scanAiContent(`ok\n${banner}\n`, { source: 'working-tree', path: 'a.py' }, []);
  assert.equal(multi[0].line, 2);
  const message = build(['t\n\nGenerated-by: ', 'Gemini <g@example.com>']);
  const trailed = scanAiMessage(message, { source: 'git-history', path: 'commit-message', commit: 'abc' }, []);
  assert.equal(trailed.length, 1);
  assert.equal(trailed[0].commit, 'abc');
});
